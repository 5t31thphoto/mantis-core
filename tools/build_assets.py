"""MantisCore asset builder.
Usage: python tools/build_assets.py src/ui/mantis_assets.h <SD card>/mantiscore
Regenerates the embedded mascot/nixie/settings assets and the SD backgrounds from tools/art/."""
import os, struct, sys
from PIL import Image, ImageDraw, ImageFilter, ImageChops
sys.path.insert(0, os.path.dirname(__file__))
OUT_H = sys.argv[1]; OUT_SD = sys.argv[2]
ART = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'art')
os.makedirs(OUT_SD, exist_ok=True)
def c565(r,g,b): return ((r>>3)<<11)|((g>>2)<<5)|(b>>3)
def arr(name, ctype, vals, per=16):
    s=f"static const {ctype} {name}[{len(vals)}] PROGMEM = {{\n"
    for i in range(0,len(vals),per): s+="  "+",".join(str(v) for v in vals[i:i+per])+",\n"
    return s+"};\n"
def write_mg(img, path):
    img=img.convert('RGB').resize((320,240))
    with open(path,'wb') as f:
        f.write(b'MG01'+struct.pack('<HH',320,240))
        f.write(b''.join(struct.pack('<H',c565(*p)) for p in img.getdata()))
H="// Generated by tools/build_assets.py - do not edit\n#pragma once\n#include <stdint.h>\n#include <pgmspace.h>\n\n"
# ---- mascot: 16 frames, 4bpp palette (index 0 = transparent)
strip=Image.open(os.path.join(ART,'mascot_strip.png')).convert('RGBA'); FW=strip.width//16; FH=strip.height
# align frames horizontally by head centroid (top 35% of opaque pixels)
frames=[strip.crop((i*FW,0,(i+1)*FW,FH)) for i in range(16)]
def headx(f):
    a=f.split()[3]; xs=[x for y in range(int(FH*0.35)) for x in range(FW) if a.getpixel((x,y))>0]
    return sum(xs)/len(xs) if xs else FW/2
hx=[headx(f) for f in frames]; ref=sum(hx)/16; PADW=FW+12
al=[]
for f,h in zip(frames,hx):
    c=Image.new('RGBA',(PADW,FH),(0,0,0,0)); c.paste(f,(6+round(ref-h),0),f); al.append(c)
big=Image.new('RGBA',(PADW*16,FH)); [big.paste(f,(i*PADW,0)) for i,f in enumerate(al)]
rgb=big.convert('RGB'); pal_img=rgb.quantize(15, method=Image.Quantize.MEDIANCUT)
pal=pal_img.getpalette()[:45]; idx=list(pal_img.getdata()); alpha=list(big.split()[3].getdata())
pix=[(0 if a<128 else i+1) for i,a in zip(idx,alpha)]
packed=[]
for fr in range(16):
    for y in range(FH):
        row=[pix[y*PADW*16+fr*PADW+x] for x in range(PADW)]
        if len(row)%2: row.append(0)
        packed+= [ (row[i]<<4)|row[i+1] for i in range(0,len(row),2)]
H+=f"#define MASCOT_W {PADW}\n#define MASCOT_H {FH}\n#define MASCOT_FRAMES 16\n#define MASCOT_STRIDE {(PADW+1)//2}\n"
H+=arr("MASCOT_PAL","uint16_t",[0]+[c565(*pal[i*3:i*3+3]) for i in range(15)])
H+=arr("MASCOT_PIX","uint8_t",packed,32)
# ---- nixie: scene to SD, additive glyphs embedded
import nixie_build as nb
write_mg(nb.scene, os.path.join(OUT_SD,'nixie.mg'))
PAD=6; tubes=[]
for sx in nb.SOCK_X:
    x0,y0=nb.to_screen(sx+nb.WIN[0],nb.SOCK_Y+nb.WIN[1]); x1,y1=nb.to_screen(sx+nb.WIN[2],nb.SOCK_Y+nb.WIN[3]); tubes.append((x0,y0,x1-x0,y1-y0))
gw,gh=tubes[0][2],tubes[0][3]
H+=f"#define NIXIE_PAD {PAD}\n#define NIXIE_GW {gw+2*PAD}\n#define NIXIE_GH {gh+2*PAD}\n"
H+="static const int16_t NIXIE_TUBE_XY[5][2] = {"+",".join(f"{{{x-PAD},{y-PAD}}}" for x,y,_,_ in tubes)+"};\n"
glyph_vals=[]
for key in list(range(10))+[':']:
    g=nb.G[key]
    if key==':':
        w=max(4,gw//3); g=g.resize((w,round(g.height*w/g.width)),Image.LANCZOS)
        if g.height>gh: g=g.resize((round(g.width*gh/g.height),gh),Image.LANCZOS)
        L=Image.new('RGB',(gw,gh)); L.paste(g,((gw-g.width)//2,(gh-g.height)//2)); g=L
    else: g=g.resize((gw,gh),Image.LANCZOS)
    L=Image.new('RGB',(gw+2*PAD,gh+2*PAD)); L.paste(g,(PAD,PAD))
    L=ImageChops.add(L.filter(ImageFilter.GaussianBlur(3)),L)
    glyph_vals+=[c565(*p) for p in L.getdata()]
H+="// 11 additive glyphs: 0-9 then colon\n"+arr("NIXIE_GLYPHS","uint16_t",glyph_vals)
# ---- loading background to SD
write_mg(Image.open(os.path.join(ART,'loading_bg.jpg')).resize((440,240),Image.LANCZOS).crop((60,0,380,240)), os.path.join(OUT_SD,'loading.mg'))
# ---- settings icon 64x64 (RGB565 + A8)
S=64; K=4; B=S*K
ic=Image.new('RGBA',(B,B),(0,0,0,0)); d=ImageDraw.Draw(ic)
for y in range(B):  # purple vertical gradient
    t=y/B; d.line((0,y,B,y),fill=(int(0x7a-0x30*t),0,int(0x7a-0x30*t),255))
m=Image.new('L',(B,B),0); ImageDraw.Draw(m).rounded_rectangle((0,0,B-1,B-1),radius=56,fill=255)
import math
gear=Image.new('L',(B,B),0); gd=ImageDraw.Draw(gear); cx=cy=B/2
pts=[]
for i in range(48):
    a=i/48*2*math.pi; r=B*0.36 if (i//3)%2==0 else B*0.28
    pts.append((cx+r*math.cos(a),cy+r*math.sin(a)))
gd.polygon(pts,fill=255); gd.ellipse((cx-B*0.12,cy-B*0.12,cx+B*0.12,cy+B*0.12),fill=0)
glow=gear.filter(ImageFilter.GaussianBlur(10))
ic=Image.composite(Image.new('RGBA',(B,B),(0,255,0,255)),ic,glow.point(lambda v:v//2))
ic=Image.composite(Image.new('RGBA',(B,B),(60,255,60,255)),ic,gear)
ic.putalpha(m); ic=ic.resize((S,S),Image.LANCZOS)
d=list(ic.getdata())
H+=arr("SETTINGS_ICON_RGB","uint16_t",[c565(r,g,b) for r,g,b,a in d])+arr("SETTINGS_ICON_A","uint8_t",[a for *_,a in d],32)
open(OUT_H,'w').write(H)
print("ok", os.path.getsize(OUT_H)//1024, "KB header")
