"""Builds the default Music tile icon (64x64 RGB565 + alpha) from the extras icon sheet.
Usage: python tools/music_icon_build.py src/ui/mantis_music_assets.h
(/icons/mp3.mi on the SD card replaces it at runtime.)"""
import os, sys
from PIL import Image, ImageDraw
HERE = os.path.dirname(os.path.abspath(__file__))
S, K = 64, 4
src = Image.open(os.path.join(HERE, 'art', 'icon_sheet_extras.jpg')).convert('RGB')
crop = src.crop((611, 55, 685, 129)).resize((S * K, S * K), Image.LANCZOS).convert('RGBA')
m = Image.new('L', (S * K, S * K), 0)
ImageDraw.Draw(m).rounded_rectangle((0, 0, S * K - 1, S * K - 1), radius=56, fill=255)
crop.putalpha(m)
ic = crop.resize((S, S), Image.LANCZOS)
c565 = lambda r, g, b: ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
px = list(ic.getdata())
def arr(name, ctype, vals, per=16):
    s = f"static const {ctype} {name}[{len(vals)}] PROGMEM = {{\n"
    for i in range(0, len(vals), per): s += "  " + ",".join(str(v) for v in vals[i:i + per]) + ",\n"
    return s + "};\n"
h = "// Generated by tools/music_icon_build.py - do not edit\n#pragma once\n#include <stdint.h>\n#include <pgmspace.h>\n\n"
h += arr("MUSIC_ICON_RGB", "uint16_t", [c565(r, g, b) for r, g, b, a in px]) + arr("MUSIC_ICON_A", "uint8_t", [a for *_, a in px], 32)
open(sys.argv[1], 'w').write(h)
ic.save('/tmp/music_icon_64.png')
print('ok')
