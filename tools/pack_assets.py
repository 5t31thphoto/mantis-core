"""Splits the generated art headers into firmware defines + an SD-card asset pack.

  tools/generated/mantis_assets.h          (from build_assets.py)
  tools/generated/mantis_weather_assets.h  (from weather_build.py)
  tools/generated/mantis_music_assets.h    (from music_icon_build.py)
      -> src/ui/<same names>.h      defines, geometry, small tables + extern pointers for big arrays
      -> src/ui/mantis_asset_pack.cpp  pointer definitions + table the loader fills
      -> sd_card/mantiscore/assets.bin   the big arrays

Run after any of the generators:  python tools/pack_assets.py
The pack carries an id (CRC32 of its contents) that is compiled into the firmware, so a pack from a
different build is rejected and the UI uses its drawn fallbacks instead of wrong data.
"""
import os, re, struct, zlib
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
HEADERS = ['mantis_assets.h', 'mantis_weather_assets.h', 'mantis_music_assets.h']
BIG = 512  # arrays with more elements than this go to the SD pack
CTYPE = {'uint16_t': ('<H', 2), 'uint8_t': ('<B', 1)}
ARR = re.compile(r'static const (uint16_t|uint8_t) (\w+)\[(\d+)\] PROGMEM = \{(.*?)\};\n', re.S)

entries = []  # (name, ctype, count, bytes)
for h in HEADERS:
    txt = open(os.path.join(HERE, 'generated', h)).read()
    def repl(m):
        ctype, name, n, body = m.group(1), m.group(2), int(m.group(3)), m.group(4)
        if n <= BIG: return m.group(0)
        vals = [int(v) for v in body.replace('\n', '').split(',') if v.strip()]
        assert len(vals) == n, name
        fmt, size = CTYPE[ctype]
        entries.append((name, ctype, n, b''.join(struct.pack(fmt, v) for v in vals)))
        return f"extern const {ctype} *{name}; // {n} values, loaded from /mantiscore/assets.bin (nullptr if missing)\n"
    out = ARR.sub(repl, txt)
    out = out.replace('// Generated by', '// Split by tools/pack_assets.py from tools/generated/' + h + '. Generated by', 1)
    open(os.path.join(ROOT, 'src', 'ui', h), 'w').write(out)

# pack: "MCAP" u32 id u16 count, then count * (name[24], u32 offset, u32 size), then data (4-aligned)
data = b''; table = []
for name, ctype, n, blob in entries:
    while len(data) % 4: data += b'\0'
    table.append((name, len(data), len(blob))); data += blob
pack_id = zlib.crc32(data) & 0xFFFFFFFF
hdr_len = 10 + 32 * len(table)
pad = (4 - hdr_len % 4) % 4
blob = b'MCAP' + struct.pack('<IH', pack_id, len(table))
for name, off, size in table:
    blob += name.encode().ljust(24, b'\0')[:24] + struct.pack('<II', hdr_len + pad + off, size)
blob += b'\0' * pad + data
sd = os.path.join(ROOT, 'sd_card', 'mantiscore'); os.makedirs(sd, exist_ok=True)
open(os.path.join(sd, 'assets.bin'), 'wb').write(blob)

cpp = ['// Generated by tools/pack_assets.py - do not edit', '#include "mantis_asset_pack.h"', '']
for h in HEADERS: cpp.append(f'#include "{h}"')
cpp.append('')
for name, ctype, n, _ in entries: cpp.append(f'const {ctype} *{name} = nullptr;')
cpp += ['', 'const McAssetEntry mcAssetTable[] = {']
for name, ctype, n, arr_bytes in entries: cpp.append(f'    {{"{name}", (const void **)&{name}, {len(arr_bytes)}u}},')
cpp += ['};', f'const int mcAssetCount = {len(entries)};', f'const uint32_t mcAssetPackId = 0x{pack_id:08X}u;', '']
open(os.path.join(ROOT, 'src', 'ui', 'mantis_asset_pack.cpp'), 'w').write('\n'.join(cpp))
print(f'{len(entries)} arrays, {len(blob)} bytes -> sd_card/mantiscore/assets.bin (id {pack_id:08X})')
for name, ctype, n, b in entries: print(f'  {name:22} {len(b):7} bytes')
